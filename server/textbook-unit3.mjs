export const TEXTBOOK_UNIT3 = { "lesson-1": LESSON_1, "lesson-2": LESSON_2, "lesson-3": LESSON_3 };

// Applies the book layer on top of the assembled demo content.
export function applyTextbook(id, content) {
  const book = TEXTBOOK_UNIT3[id];
  if (!book || !content) return content;
  const resources = content.resources.map((r) => {
    const patch = book.resources[r.id];
    if (!patch) return r;
    const { addLocations = [], rename = {}, locations, ...fields } = patch;
    const base = (locations || r.locations || []).map((l) =>
      rename[l.id] ? { ...l, name: rename[l.id] } : l,
    );
    return {
      ...r,
      ...fields,
      locations: [...base, ...addLocations.filter((a) => !base.some((b) => b.id === a.id))],
    };
  });
  for (const extra of book.newResources)
    if (!resources.some((r) => r.id === extra.id))
      resources.push({ media: { image: null, video: null }, ...structuredClone(extra) });
  const images = BOOK_IMAGES[id];
  for (const r of resources) {
    const file = images?.resources[r.id];
    if (file)
      r.media = { ...(r.media || {}), image: IMG + file, imageCredit: CREDIT };
  }
  const bookIds = new Set(book.questions.map((q) => q.id));
  return {
    ...content,
    title: book.title,
    intro: book.intro,
    summary: book.summary,
    objectives: [...book.objectives],
    concepts: book.concepts.map((c) => ({ ...c })),
    resources,
    questions: [
      ...book.questions.map((q) => structuredClone(q)),
      ...content.questions
        .filter((q) => !bookIds.has(q.id))
        .map((q) => (book.duplicates?.[q.id] ? { ...q, duplicateOf: book.duplicates[q.id] } : q)),
    ],
    sources: [
      {
        id: "textbook-unit3",
        title: `${BOOK} — ص ${book.pages}`,
        text: [book.intro, ...book.keyPoints, book.realLife].join("\n"),
        approved: false,
      },
      ...(content.sources || []).filter((s) => s.id !== "textbook-unit3"),
    ],
    legacyExtras: {
      ...(content.legacyExtras || {}),
      keyPoints: [...book.keyPoints],
      examples: [...book.examples],
      realLife: book.realLife,
      funFacts: [...book.funFacts],
      secrets: [],
      bookMap: images?.map
        ? { src: IMG + images.map[0], caption: images.map[1], credit: CREDIT }
        : null,
    },
  };
}
